"""kits/mkarch.sh helper: the importer's numbers + kits/arch.py -> firmware/gen/arch.h. Run from the drumlab folder: mkarch_gen.py TMPDIR"""
import sys, subprocess, glob, os
sys.path.insert(0, "kits")
import arch
T = sys.argv[1]
out = ["/* generated by kits/mkarch.sh from kits/arch.py: our own drum archetypes (4 columns x 8, A and B patch, 21 PO-32 wire parameters) and kit recipes */",
       "static const uint16_t arch_patch[4][8][2][21] = {"]
for c in range(4):
    out.append(" {")
    for i, (name, _) in enumerate(arch.ARCH[c]):
        pats = []
        for tag in "AB":
            f = glob.glob(f"{T}/mt/{c}{i}-*-{tag}.mtdrum")[0]
            rows = subprocess.check_output([f"{T}/mkarch", f]).decode().split()
            pats.append("{" + rows[0] + "}")
        out.append(f"  {{{pats[0]}, {pats[1]}}},   /* {name} */")
    out.append(" },")
out.append("};")
out.append("static const char *const arch_name[4][8] = {")
for c in range(4):
    out.append("    {" + ", ".join('"%s"' % n.upper() for n, _ in arch.ARCH[c]) + "},")
out.append("};")
out.append("typedef struct { const char *name; uint8_t pick[4][4]; int8_t tune; uint8_t decay; int8_t dist, noise; } kit_def_t;     /* tune: 1/100 octave; decay: percent; dist, noise: percent added */")
out.append(f"#define NKITDEF {len(arch.KITS)}")
out.append("static const kit_def_t kit_def[NKITDEF] = {")
for name, picks, m in arch.KITS:
    out.append(f'    {{"{name}", {{' + ", ".join("{" + ", ".join(map(str, r)) + "}" for r in picks) + f"}}, {round(m['tune']*100)}, {round(m['decay']*100)}, {m['dist']}, {m['noise']}}},")
out.append("};")
open("firmware/gen/arch.h", "w").write("\n".join(out) + "\n")
print("firmware/gen/arch.h")
