#!/usr/bin/env python3
"""Writes firmware/gen/drum_tables.h: sine, exp2 and log2 tables for drum.c (no float on the device)."""
import math
from pathlib import Path

out = ["/* generated by tools/gen_drum_tables.py */"]

def arr(name, ctype, vals):
    out.append(f"static {ctype} {name}[{len(vals)}] = {{")   # in RAM: the flash cache is slow for tables
    for i in range(0, len(vals), 8):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + 8]) + ",")
    out.append("};")

arr("dr_sin", "int32_t", [round(math.sin(2 * math.pi * i / 1024) * (1 << 30)) for i in range(1025)])
arr("dr_exp2", "uint32_t", [round(2 ** (i / 256) * (1 << 30)) for i in range(257)])
arr("dr_log2", "uint32_t", [round(math.log2(1 + i / 256) * (1 << 24)) for i in range(257)])
import math as m
L = m.log2
consts = {
    "K_L2_1000": round(L(1000) * (1 << 24)),          # log2(1000), Q24
    "K_L2_10": round(L(10) * (1 << 24)),
    "K_TURN20": round((L(20) + 32 - L(44100)) * (1 << 24)),      # turns/sample at 20 Hz, Q32 out
    "K_TURN_2000": round((L(2000) + 32 - L(44100)) * (1 << 24)),
    "K_L2_ATK": round((L(44100 * 256) - 1.4 * L(10)) * (1 << 24)),    # attack samples Q8 = x * 2^(..)
    "K_L2_DCY": round(L(441 * 256) * (1 << 24)),
    "K_L2_DSTEP": round(L(9.965784284662087 / 441) * (1 << 24)),
    "K_ATK_FLOOR27": round(L(1000) * (1 << 27)),
    "K_MSTEP": round(L(1000) * 3 / 44100 * (1 << 27)),
    "K_L2_NOISE_E": round(L(2 * m.pi * L(m.e) * 20000 / 44100) * (1 << 24)),
    "K_L2_Q0": round(L(0.1) * (1 << 24)),
    "K_L2_Q_X": round(L(100000) * (1 << 24)),
    "K_L2_FREQ_SR": round(L(44100) * (1 << 24)),
    "K_L2_SR": round(L(44100) * (1 << 24)),
    "K_DB20": round(L(10) / 20 * (1 << 24)),
    "K_DB40": round(L(10) / 40 * (1 << 24)),
    "K_L2_RING": round(-L(44100) * (1 << 24)),
    "K_L2_10000": round(L(10000) * (1 << 24)),
    "K_L2_D112896": round(L(112896) * (1 << 24)),
    "K_L2_ATK_X": round(2.4 * L(10) * (1 << 24)),
}
for k, v in consts.items():
    out.append(f"#define {k} {v}")
out.append(f"#define K_ATKSTEP {round(L(1000) * (1 << 27) * 256)}ull")
Path(__file__).resolve().parents[1].joinpath("firmware/gen/drum_tables.h").write_text("\n".join(out) + "\n")
