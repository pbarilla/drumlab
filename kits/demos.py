#!/usr/bin/env python3
"""Our own demo projects and lessons (patterns written for this repo, grooves anyone may play) -> firmware/gen/demos.h.
A pattern is written as {sound: [steps]} with accents as {sound: [steps]}; sounds are the 16 places of a kit (sound 0-3 = the top row).
Lane = sound % 4, the sound's row = sound // 4 (that is how the PO-32 shares a column)."""
import sys

def pat(hits, acc=()):
    """hits: {sound: [steps 0-15]}; acc: steps with an accent (all lanes) -> 4 x 16 trig bytes + 4 x 16 x 2 lock + acc mask + 16 fx words, as C"""
    trig = [[0] * 16 for _ in range(4)]
    for s, steps in hits.items():
        for st in steps:
            trig[s & 3][st] = 1 | ((s >> 2) << 4)
    a = 0
    for st in acc: a |= 1 << st
    return trig, a

