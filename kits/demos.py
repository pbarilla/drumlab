def c_pat(p):
    trig, a = p
    t = ", ".join("{" + ", ".join(str(v) for v in row) + "}" for row in trig)
    return "{{" + t + "}, %d}" % a
if __name__ == "__main__":
    out = ["/* generated by kits/demos.py: our own demo projects and lessons. kit: 0 = LAB-1, n = the recipe n - 1 of arch.h */",
           "typedef struct { uint8_t trig[4][16]; uint16_t acc; } dpat_t;",
           "typedef struct { const char *name; uint8_t kit, bpm, swing, npat, nchain; dpat_t pat[4]; uint8_t chain[16]; } demo_t;",
           "#define NDEMO %d" % len(DEMOS), "static const demo_t demos[NDEMO] = {"]
